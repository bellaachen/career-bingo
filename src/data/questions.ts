export const QUESTIONS: Prompt[] = (Object.keys(bank) as RoleId[]).flatMap((role) =>
  bank[role].map(([id, en, zh]) => ({ id, role, text: { en, 'zh-TW': zh } })),
)

const byId = new Map(QUESTIONS.map((q) => [q.id, q]))
const byRole = new Map<RoleId, string[]>()
for (const q of QUESTIONS) {
  const list = byRole.get(q.role) ?? []
  list.push(q.id)
  byRole.set(q.role, list)
}

export function getPrompt(id: string): Prompt | undefined {
  return byId.get(id)
}

export function poolFor(role: RoleId): readonly string[] {
  return byRole.get(role) ?? []
}
